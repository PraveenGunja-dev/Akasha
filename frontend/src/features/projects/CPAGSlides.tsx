/* ── Formatting ── */
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
                'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

export const MONTH_LABEL = (m: string) => {
  const [y, mm] = m.split('-');
  return `${MONTHS[Number(mm) - 1]}-${y.slice(2)}`;
};
export const DATE = (s: string | null | undefined) =>
  s ? new Date(s).toLocaleDateString('en-GB',
    { day: '2-digit', month: 'short', year: '2-digit' }) : '—';
export const NUM = (n: number | null | undefined, dp = 0) =>
  n === null || n === undefined ? '—'
    : n.toLocaleString('en-IN', { minimumFractionDigits: dp, maximumFractionDigits: dp });
export const PCT = (n: number | null | undefined, dp = 1) =>
  n === null || n === undefined ? '—' : `${n.toFixed(dp)}%`;

/* echarts-for-react measures once at mount and then listens only to window
   resizes. The slide stage rescales without the window changing, so the
   container is observed directly. */
export const Chart = ({ option, height }: { option: any; height: number }) => {
  const ref = useRef<any>(null);
  const box = useRef<HTMLDivElement>(null);
  const { themeName } = useChartTheme();
  useEffect(() => {
    if (!box.current) return;
    const ro = new ResizeObserver(() => ref.current?.getEchartsInstance()?.resize());
    ro.observe(box.current);
    return () => ro.disconnect();
  }, []);
  return (
    <div ref={box} className="w-full" style={{ height }}>
      <ReactECharts ref={ref} option={option} theme={themeName} notMerge lazyUpdate
        style={{ height: '100%', width: '100%' }} />
    </div>
  );
};

