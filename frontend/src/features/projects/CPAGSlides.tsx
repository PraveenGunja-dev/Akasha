const bucketRemark = (b: any, p: any): string => {
  const within = b.withinBucketPct;
  switch (b.key) {
    case 'statutory': {
      const done = p.approvalsDone ?? 0, tot = p.approvalsTotal ?? 0;
      return `${done} of ${tot} approvals complete; ${tot - done} outstanding.`;
    }
    case 'engineering': {
      const e = p.engineering;
      return e?.total
        ? `${e.completed} of ${e.total} engineering activities complete.`
        : 'Engineering activities complete.';
    }
    case 'procurement': {
      const pkgs = p.packages?.length ?? 0;
      const recd = (p.packages ?? []).filter((pk: any) =>
        (pk.milestones ?? []).some((m: any) =>
          m.name.toLowerCase().includes('receipt at site') && m.actualFinish)).length;
      return `${recd} of ${pkgs} packages have receipts at site; `
        + `₹${NUM(p.deliveredCr, 1)} Cr of ₹${NUM(p.orderCr, 1)} Cr delivered.`;
    }
    default: {
      const q = p.quality;
      return `${PCT(within, 0)} of construction scope earned; `
        + `${NUM(q?.openNc)} non-conformances open against ${NUM(q?.rfiTotal)} inspections.`;
    }
  }
};

